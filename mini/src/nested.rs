//! **Nested inductives: specialise, check, restore.**
//!
//! # What a nested declaration is, as the export hands it over
//!
//! `inductive Tree | leaf | node : List Tree → Tree` arrives as **one**
//! `Declar::Inductive` with `all = [Tree]` and `numNested = 1`, whose
//! constructor `Tree.node` is typed at the **real** `List Tree`, plus **two**
//! recursors: `Tree.rec`, whose rules are `Tree`'s constructors, and
//! `Tree.rec_1`, whose rules are **`List`'s** — a recursor for one type that
//! ι-reduces on another type's constructors. Both carry `all = [Tree]`, two
//! motives and four minors.
//!
//! `mini/tests/fixtures/nested_shapes.lean` carries four such declarations and
//! its export carries all nine of their recursors; every claim above is read
//! off that file and not off the documentation.
//!
//! # What this module does
//!
//! Lean's own elaborator builds `Tree` by *specialising*: the container is
//! copied, at the arguments the occurrence uses, into a **mutual block**
//!
//! ```text
//! Tree            : Type          Tree._nested.1      : Type
//!   leaf : Tree                     nil  : Tree._nested.1
//!   node : Tree._nested.1 → Tree    cons : Tree → Tree._nested.1 → Tree._nested.1
//! ```
//!
//! which is an ordinary mutual inductive that [`crate::kernel::add`] already
//! checks and already generates recursors for. Those recursors are
//! `Tree.rec` and `Tree._nested.1.rec`, and **restoring** them — rewriting the
//! copy back to `List Tree`, its constructors back to `List.nil Tree` /
//! `List.cons Tree`, and `Tree._nested.1.rec` to `Tree.rec_1` — produces
//! exactly the two recursors the export declares. That equality is not
//! asserted here; it is measured, by the export oracle
//! (`mini/tests/mutual.rs`'s `the_generated_recursors_are_the_ones_lean_exports`,
//! which compares mini's generated recursor against Lean's own for every
//! fixture), and `mini/tests/nested.rs` is what puts the nested fixtures in
//! front of it.
//!
//! # What is *not* justified by this module, stated plainly
//!
//! The block that gets checked is the specialised one. The declarations that
//! get installed are the restored ones, and the restoration is a **rewrite,
//! not a derivation**: nothing here proves `List Tree` and `Tree._nested.1`
//! are the same type, because they are not — they are isomorphic, by a pack /
//! unpack pair, and the round trip is propositional and not definitional
//! (`mini/tests/nested.rs`'s
//! `the_round_trip_the_encoding_would_need_is_not_definitional` is that
//! sentence as a check the kernel runs).
//!
//! So `Tree.rec_1`'s ι rule on `List.cons` is, at the acceptance axis, an
//! **assumption transported along an isomorphism this module does not check**.
//! Discharging it is the evidence axis's job: a certificate that the two
//! interpretations agree. Until that lands, a file with a nested inductive is
//! accepted only behind [`crate::convert::LoadOptions::nested`], which the
//! corpus never sets — the same gating `--mutual` had for the same reason.
//!
//! # The model, written out by hand
//!
//! `mini/tests/fixtures/nested_model.lean` is the encoding this module's rules
//! would have to be interpreted by, written out as an export and checked by
//! Lean and by mini: the specialised block as an ordinary `mutual`, `Tree` and
//! its constructors as `def`s over it, `pack`/`unpack` and both round trips as
//! theorems, both recursors as `def`s at the types the export declares, and all
//! four ι rules **proved**. So the rule installed here is satisfiable: a
//! `Tree.rec_1` obeying it exists over the real `List`.
//!
//! Two of the four rules come out definitionally under pack/unpack (`leaf`, and
//! `rec_1` on `List.nil`) and two do not (`Tree.node`, and `rec_1` on
//! `List.cons`); each of the two is **one** transport lemma, proved by `Eq.rec`
//! on the round trip landing at `Eq.refl`, with proof irrelevance closing the
//! triangle identity that Lean 3's compiler had to rewrite with a simp set
//! (`LEAN3-INDUCTIVE-COMPILER.md` §4). `mini/tests/nested.rs`'s
//! `two_of_the_four_model_iota_rules_are_definitional_and_two_are_not` is that
//! table as a check the kernel runs.
//!
//! # The keying, and what it does and does not reach
//!
//! [`crate::nested_splice`] puts that model — generated by
//! [`crate::nested_ev::iso`] rather than written out — into the run beside the
//! primitives this module installs, and keys `⟦T⟧`, `⟦T.ctorᵢ⟧` and
//! `⟦T.rec_k⟧` onto it through `IndApparatus::model_of`. `zoneb`'s
//! `ind-spec(T: nested occurrence)` is no longer the answer for a nested
//! declaration: `nested_shapes` derives every one of its pairs, and a
//! declaration with no model declines by the shape that stopped it.
//!
//! **What that keying does not by itself do is make the rules fire on the
//! evidence axis.** `⟦T.rec_k⟧` is the model's recursor, and the model's ι
//! rules are theorems beside it; turning one into the equation a conversion
//! site can consume is [`crate::eq_cash`], and putting that on the ι dispatch
//! is the arm this module's rules are still waiting for.
//!
//! # The boundary
//!
//! This module is a **black box over the evidence layer**, on the same terms
//! as [`crate::mutual_aux`] and checked by the same rule
//! (`ci/check-nested-blackbox.sh`): it emits Lean-world syntax, asks
//! [`crate::kernel::add`] whether it is well-formed, and reads back only
//! *zone A's* syntax — a `ConstantInfo`'s declared type and rules. It never
//! names a certificate.

use crate::env::{instantiate_lparams, ConstantInfo, Declaration, Environment, IndType};
use crate::expr::{app_n, bvars, get_app, has_bvar, konst, substs, Expr, Level, Name, E};
use std::collections::HashMap;

type R<T> = Result<T, String>;

/// One specialised copy of a container — Lean 3 called it the *mimic*.
#[derive(Clone, Debug)]
pub struct Mimic {
    /// The fresh block member, e.g. `Tree._nested.1`.
    pub name: Name,
    /// The container applied to the parameters the occurrence uses, written
    /// **relative to the block's parameter telescope**: `List Tree` for
    /// `Tree`, and `List (Tree #0)` for a `Tree` with one parameter. Its only
    /// loose bound variables are the block's parameters.
    pub occ: E,
    /// `(the copy's constructor, the real constructor at those parameters)` —
    /// `(Tree._nested.1.cons, List.cons Tree)`.
    pub ctors: Vec<(Name, E)>,
}

/// The specialised block, and everything needed to restore it.
#[derive(Clone, Debug)]
pub struct Plan {
    /// Member 0 is the declared type itself, with its constructor types
    /// specialised; members 1.. are the mimics, **in discovery order**.
    pub types: Vec<IndType>,
    pub mimics: Vec<Mimic>,
}

impl Plan {
    /// The name the export gives member `k`'s recursor: `T.rec`, `T.rec_1`, …
    ///
    /// Read off `nested_shapes.ndjson`: `DTree`'s three recursors are
    /// `DTree.rec` (major `DTree`), `DTree.rec_1` (major `List (List DTree)`)
    /// and `DTree.rec_2` (major `List DTree`), which is member order.
    pub fn rec_name(root: &Name, k: usize) -> Name {
        if k == 0 {
            Name::str(root, "rec")
        } else {
            Name::str(root, &format!("rec_{k}"))
        }
    }
}

/// **Is this declaration nested, and if so how is it specialised?**
///
/// `Ok(None)` means no constructor mentions the type under a foreign
/// inductive — an ordinary declaration, which the caller must go on handling
/// exactly as before. `Err` means the declaration *is* nested and this module
/// cannot express it; the caller turns that into a rejection with the reason
/// attached, never into a silent fallback.
pub fn plan(
    env: &Environment,
    lparams: &[Name],
    num_params: u32,
    types: &[IndType],
) -> R<Option<Plan>> {
    let root = match types.first() {
        Some(t) => t.name.clone(),
        None => return Ok(None),
    };
    let us: std::rc::Rc<[Level]> =
        lparams.iter().map(|n| Level::Param(n.clone())).collect::<Vec<_>>().into();
    let mut sp = Sp {
        env,
        num_params,
        us,
        members: types.iter().map(|t| t.name.clone()).collect(),
        mimics: Vec::new(),
        root: root.clone(),
        // The parameter binder types of the block, peeled from the first
        // member's own type. Every mimic is declared over the same telescope.
        params: peel_params(&types[0].ty, num_params)?,
    };

    // Member 0..n-1's constructors, then each mimic's as it is created — a
    // FIFO worklist, because that is the order Lean numbers the motives in.
    // `DTree.node : List (List DTree) → DTree` yields `List (List DTree)` from
    // the declaration and `List DTree` from *that copy's* `cons`, and the
    // export's `motive_2`/`motive_3` are in exactly that order.
    let mut out: Vec<IndType> = Vec::with_capacity(types.len());
    for t in types {
        let mut cs = Vec::with_capacity(t.ctors.len());
        for (cn, cty) in &t.ctors {
            cs.push((cn.clone(), sp.spec(cty, 0)?));
        }
        out.push(IndType { name: t.name.clone(), ty: t.ty.clone(), ctors: cs });
    }
    if sp.mimics.is_empty() {
        return Ok(None)
    }
    if types.len() > 1 {
        return Err(format!(
            "{root} is both a mutual block and nested; mini takes one or the other"
        ))
    }
    // Each mimic's own constructors, which may create further mimics. Indexing
    // rather than iterating: the vector grows inside the loop, and that growth
    // is the depth-2 case (`DTree`) working.
    let mut k = 0usize;
    while k < sp.mimics.len() {
        let m = sp.mimics[k].clone();
        let (ty, ctors) = sp.mimic_decl(&m)?;
        out.push(IndType { name: m.name.clone(), ty, ctors });
        k += 1;
    }
    Ok(Some(Plan { types: out, mimics: sp.mimics }))
}

/// **Specialise, check as a mutual block, restore, install.**
///
/// The whole of the checker interaction is the one `kernel::add` below: this
/// module builds a `Declaration::Mutual` and asks whether it is well-formed.
/// What comes back is read for its *syntax* — a member's constructor types, a
/// recursor's declared type and rules — and nothing else.
pub fn add(
    env: &mut Environment,
    lparams: &[Name],
    num_params: u32,
    types: &[IndType],
    plan: &Plan,
) -> R<()> {
    let root = types[0].name.clone();
    // A scratch environment, because the mimics are **not** declarations the
    // export makes and must not survive into the real one: `Tree._nested.1` is
    // this module's name for `List Tree`, and a consumer that found it in the
    // environment would be looking at an artefact of the encoding.
    let mut scratch = env.clone();
    crate::kernel::add(
        &mut scratch,
        &Declaration::Mutual {
            lparams: lparams.to_vec(),
            num_params,
            types: plan.types.clone(),
        },
    )
    .map_err(|e| format!("{e}\n… while checking the specialised block of {root}"))?;

    // The restoration table: every name the specialisation introduced, with
    // how many leading arguments it consumes and what it becomes.
    let mut heads: HashMap<Name, (u32, E)> = HashMap::new();
    for (k, m) in plan.mimics.iter().enumerate() {
        heads.insert(m.name.clone(), (num_params, m.occ.clone()));
        for (mc, real) in &m.ctors {
            heads.insert(mc.clone(), (num_params, real.clone()));
        }
        heads.insert(
            Name::str(&m.name, "rec"),
            (0, konst(Plan::rec_name(&root, k + 1), rec_levels(&scratch, &m.name)?)),
        );
    }

    // Member 0 keeps its own name, so its constructor types must restore to
    // the types the export declared. Asserted rather than assumed: a
    // specialisation that dropped or mangled an occurrence would otherwise
    // install a constructor at a type nobody asked for.
    for (cn, cty) in &types[0].ctors {
        let got = restore(&heads, get_ty(&scratch, cn)?);
        if got != *cty {
            return Err(format!(
                "restoring {cn} did not give back its declared type:\n  declared {cty}\n  restored {got}"
            ))
        }
    }

    // Install: the declared type, its constructors at their **export** types,
    // and one recursor per block member under the export's name.
    let ConstantInfo::Inductive { ty, num_indices, ctors, is_unit, .. } =
        scratch.get(&root).cloned().ok_or_else(|| format!("{root} vanished"))?
    else {
        return Err(format!("{root} did not come back as an inductive"))
    };
    env.insert_new(
        root.clone(),
        ConstantInfo::Inductive {
            lparams: lparams.to_vec(),
            ty,
            num_params,
            num_indices,
            ctors,
            is_unit,
        },
    )?;
    for (cn, cty) in &types[0].ctors {
        env.insert_new(
            cn.clone(),
            ConstantInfo::Opaque { lparams: lparams.to_vec(), ty: cty.clone() },
        )?;
        env.owners.insert(cn.clone(), root.clone());
    }
    for k in 0..plan.types.len() {
        let member = &plan.types[k].name;
        let src = Name::str(member, "rec");
        let ConstantInfo::Recursor {
            lparams: rl,
            ty,
            num_params: np,
            num_motives,
            num_minors,
            num_indices,
            rules,
            k_type,
        } = scratch.get(&src).cloned().ok_or_else(|| format!("{src} was not generated"))?
        else {
            return Err(format!("{src} did not come back as a recursor"))
        };
        let name = Plan::rec_name(&root, k);
        env.owners.insert(name.clone(), root.clone());
        env.insert_new(
            name,
            ConstantInfo::Recursor {
                lparams: rl,
                ty: restore(&heads, &ty),
                num_params: np,
                num_motives,
                num_minors,
                num_indices,
                rules: rules
                    .iter()
                    .map(|(c, rhs)| (restore_ctor_name(&heads, c), restore(&heads, rhs)))
                    .collect(),
                k_type: k_type.map(|t| restore(&heads, &t)),
            },
        )?;
    }
    Ok(())
}

/// The level parameters mini gave a member's generated recursor.
fn rec_levels(env: &Environment, member: &Name) -> R<std::rc::Rc<[Level]>> {
    let n = Name::str(member, "rec");
    let ci = env.get(&n).ok_or_else(|| format!("{n} was not generated"))?;
    Ok(ci.lparams().iter().map(|p| Level::Param(p.clone())).collect::<Vec<_>>().into())
}

fn get_ty<'a>(env: &'a Environment, n: &Name) -> R<&'a E> {
    env.get(n).map(ConstantInfo::ty).ok_or_else(|| format!("{n} was not declared"))
}

/// A rule is keyed by a **constructor name**, and the restored key is the real
/// container's constructor — `Tree._nested.1.cons` becomes `List.cons`, which
/// is the name the export's `Tree.rec_1` rules carry.
fn restore_ctor_name(heads: &HashMap<Name, (u32, E)>, c: &Name) -> Name {
    match heads.get(c) {
        Some((_, repl)) => match &*get_app(repl).0 {
            Expr::Const(n, _) => n.clone(),
            _ => c.clone(),
        },
        None => c.clone(),
    }
}

/// Rewrite every name the specialisation introduced back to what it stands
/// for. A head that consumes `p` arguments has them substituted into its
/// replacement — that is how `Tree._nested.1 α` becomes `List (Tree α)` under
/// a parameter — and a head that consumes none is a plain rename.
pub fn restore(heads: &HashMap<Name, (u32, E)>, e: &E) -> E {
    if heads.is_empty() {
        return e.clone()
    }
    match &**e {
        // A bare head with parameters still to consume is left **unrestored**
        // on purpose: it cannot occur in a well-formed type, and an internal
        // name surviving into the environment is caught by the export oracle,
        // where a silently substituted body with loose variables would not be.
        Expr::Const(n, _) => match heads.get(n) {
            Some((0, repl)) => repl.clone(),
            _ => e.clone(),
        },
        Expr::App(..) => {
            let (h, args) = get_app(e);
            let args: Vec<E> = args.iter().map(|a| restore(heads, a)).collect();
            if let Expr::Const(n, _) = &*h {
                if let Some((take, repl)) = heads.get(n) {
                    let take = *take as usize;
                    if args.len() >= take {
                        let head = substs(repl, &args[..take], 0);
                        return app_n(head, &args[take..])
                    }
                }
            }
            app_n(restore(heads, &h), &args)
        }
        Expr::Lam { ty, body } => crate::expr::lam(restore(heads, ty), restore(heads, body)),
        Expr::Forall { ty, body } => {
            crate::expr::forall(restore(heads, ty), restore(heads, body))
        }
        Expr::Let { ty, val, body } => std::rc::Rc::new(Expr::Let {
            ty: restore(heads, ty),
            val: restore(heads, val),
            body: restore(heads, body),
        }),
        Expr::Proj { ind, idx, s } => std::rc::Rc::new(Expr::Proj {
            ind: ind.clone(),
            idx: *idx,
            s: restore(heads, s),
        }),
        Expr::BVar(..) | Expr::Sort(..) | Expr::NatLit(..) | Expr::StrLit(..) => e.clone(),
    }
}

/// The block's parameter binder types, outermost first.
fn peel_params(ty: &E, num_params: u32) -> R<Vec<E>> {
    let mut out = Vec::new();
    let mut cur = ty.clone();
    for _ in 0..num_params {
        let Expr::Forall { ty, body } = &*cur.clone() else {
            return Err("inductive type has fewer binders than parameters".to_string())
        };
        out.push(ty.clone());
        cur = body.clone();
    }
    Ok(out)
}

/// The specialiser's state.
struct Sp<'a> {
    env: &'a Environment,
    num_params: u32,
    us: std::rc::Rc<[Level]>,
    members: Vec<Name>,
    mimics: Vec<Mimic>,
    root: Name,
    params: Vec<E>,
}

impl Sp<'_> {
    /// Does `e` mention a member of the block *as it stands so far*? That is
    /// the test for "this container application is a nested occurrence": a
    /// `List N` beside a `List Tree` in the same file is an ordinary type and
    /// must stay one, which `nested_shapes.lean`'s `listOfN` is there to catch.
    fn mentions_member(&self, e: &E) -> bool {
        self.members.iter().any(|m| crate::expr::has_const(m, e))
    }

    /// Specialise one expression at binder depth `d` — `d` counts *all* the
    /// binders opened so far, of which the outermost `num_params` are the
    /// block's parameters.
    fn spec(&mut self, e: &E, d: u32) -> R<E> {
        match &**e {
            Expr::App(..) | Expr::Const(..) => {
                let (h, args) = get_app(e);
                if let Expr::Const(c, ls) = &*h {
                    if let Some(np) = self.container_arity(c, &args) {
                        let occ = app_n(h.clone(), &args[..np]);
                        if self.mentions_member(&occ) {
                            // Unreachable, and a subtraction below would wrap
                            // rather than say so: an occurrence mentions a
                            // member, and a *parameter's* type cannot, so the
                            // shallowest depth one can sit at is the parameter
                            // telescope's own.
                            if d < self.num_params {
                                return Err(format!(
                                    "the nested occurrence {occ} in {} sits inside a parameter",
                                    self.root
                                ))
                            }
                            let name = self.mimic_for(&occ, c, ls, d)?;
                            let head =
                                app_n(konst(name, self.us.clone()), &bvars(self.num_params, d - self.num_params));
                            let rest: Vec<E> = args[np..]
                                .iter()
                                .map(|a| self.spec(a, d))
                                .collect::<R<Vec<E>>>()?;
                            return Ok(app_n(head, &rest))
                        }
                    }
                }
                let args: Vec<E> =
                    args.iter().map(|a| self.spec(a, d)).collect::<R<Vec<E>>>()?;
                Ok(app_n(h, &args))
            }
            Expr::Lam { ty, body } => {
                Ok(crate::expr::lam(self.spec(ty, d)?, self.spec(body, d + 1)?))
            }
            Expr::Forall { ty, body } => {
                Ok(crate::expr::forall(self.spec(ty, d)?, self.spec(body, d + 1)?))
            }
            Expr::Let { ty, val, body } => Ok(std::rc::Rc::new(Expr::Let {
                ty: self.spec(ty, d)?,
                val: self.spec(val, d)?,
                body: self.spec(body, d + 1)?,
            })),
            Expr::Proj { ind, idx, s } => Ok(std::rc::Rc::new(Expr::Proj {
                ind: ind.clone(),
                idx: *idx,
                s: self.spec(s, d)?,
            })),
            _ => Ok(e.clone()),
        }
    }

    /// `Some(p)` when `c` is an inductive **outside** the block, applied to at
    /// least its `p` parameters. Nesting happens in a container's parameters
    /// and nowhere else — Lean 3's `find_nested_occ_in_ir_arg_type_core`
    /// enforces the same restriction — so the occurrence is the container at
    /// its parameters and any indices ride outside it.
    fn container_arity(&self, c: &Name, args: &[E]) -> Option<usize> {
        if self.members.contains(c) {
            return None
        }
        let ConstantInfo::Inductive { num_params, .. } = self.env.get(c)? else { return None };
        let np = *num_params as usize;
        if args.len() >= np {
            Some(np)
        } else {
            None
        }
    }

    /// The mimic for `occ`, created if this is the first sighting.
    fn mimic_for(&mut self, occ: &E, c: &Name, ls: &std::rc::Rc<[Level]>, d: u32) -> R<Name> {
        // `occ` lives at depth `d`; the record keeps it at the parameter
        // telescope's depth. Only the parameters may occur in it — a nested
        // occurrence that mentioned one of the constructor's own fields would
        // be a dependent copy, which no member of a mutual block can be.
        let k = d - self.num_params;
        for i in 0..k {
            if has_bvar(occ, i) {
                return Err(format!(
                    "the nested occurrence {occ} in {} depends on a constructor field",
                    self.root
                ))
            }
        }
        let occ = lower(occ, k);
        if let Some(m) = self.mimics.iter().find(|m| m.occ == occ) {
            return Ok(m.name.clone())
        }
        let idx = self.mimics.len() + 1;
        let name = Name::Num(std::rc::Rc::new(Name::str(&self.root, "_nested")), idx as u64);
        if self.env.get(&name).is_some() {
            return Err(format!("{name} is already declared"))
        }
        let ConstantInfo::Inductive { ctors, .. } =
            self.env.get(c).ok_or_else(|| format!("unknown container {c}"))?
        else {
            return Err(format!("{c} is not an inductive"))
        };
        let mut cs = Vec::with_capacity(ctors.len());
        let (_, occ_args) = get_app(&occ);
        for cn in ctors {
            let last = match cn {
                Name::Str(_, s) => s.to_string(),
                other => other.to_string(),
            };
            cs.push((
                Name::str(&name, &last),
                app_n(konst(cn.clone(), ls.clone()), &occ_args),
            ));
        }
        self.members.push(name.clone());
        self.mimics.push(Mimic { name: name.clone(), occ, ctors: cs });
        Ok(name)
    }

    /// The mimic's own declaration: the container's type and constructors at
    /// the occurrence's parameters, specialised in turn.
    fn mimic_decl(&mut self, m: &Mimic) -> R<(E, Vec<(Name, E)>)> {
        let (h, occ_args) = get_app(&m.occ);
        let Expr::Const(c, ls) = &*h else {
            return Err(format!("the occurrence {} is not headed by a constant", m.occ))
        };
        let ci = self.env.get(c).ok_or_else(|| format!("unknown container {c}"))?;
        let cls = ci.lparams().to_vec();
        // The container's type at the occurrence's parameters, under the
        // block's parameter telescope.
        // The mimic's own type is specialised too: an *indexed* container
        // whose index types mention a member would otherwise keep an
        // unspecialised occurrence in a position nothing later rewrites.
        let ty = self.at_params(&instantiate_lparams(ci.ty(), &cls, ls)?, &occ_args)?;
        let ty = self.spec(&ty, self.num_params)?;
        let ty = wrap_params(&self.params, ty);
        let mut out = Vec::with_capacity(m.ctors.len());
        for (mc, real) in &m.ctors {
            let (rh, _) = get_app(real);
            let Expr::Const(rc, _) = &*rh else {
                return Err(format!("{mc} has no real constructor"))
            };
            let rci = self.env.get(rc).ok_or_else(|| format!("unknown constructor {rc}"))?;
            let rls = rci.lparams().to_vec();
            let cty = self.at_params(&instantiate_lparams(rci.ty(), &rls, ls)?, &occ_args)?;
            let cty = self.spec(&cty, self.num_params)?;
            out.push((mc.clone(), wrap_params(&self.params, cty)));
        }
        Ok((ty, out))
    }

    /// Peel the container's own parameter binders and substitute the
    /// occurrence's arguments, leaving an expression at the block's parameter
    /// telescope.
    fn at_params(&self, ty: &E, args: &[E]) -> R<E> {
        let mut cur = ty.clone();
        for _ in 0..args.len() {
            let Expr::Forall { body, .. } = &*cur.clone() else {
                return Err(format!("container type {ty} has too few parameters"))
            };
            cur = body.clone();
        }
        Ok(substs(&cur, args, 0))
    }
}

/// Wrap `body` in the block's parameter telescope.
fn wrap_params(params: &[E], body: E) -> E {
    let mut out = body;
    for p in params.iter().rev() {
        out = crate::expr::forall(p.clone(), out);
    }
    out
}

/// Drop `k` binder levels from an expression known not to use them — the
/// inverse of [`crate::expr::shift`] at `n = 0`, which the expression module
/// has no need for anywhere else. The caller has already checked that no bound
/// variable below the cut occurs.
fn lower(e: &E, k: u32) -> E {
    if k == 0 {
        return e.clone()
    }
    lower_general(e, k, 0)
}

/// `lower`, with the cut at an arbitrary depth.
fn lower_general(e: &E, k: u32, cut: u32) -> E {
    match &**e {
        Expr::BVar(i) => {
            if *i < cut {
                e.clone()
            } else {
                crate::expr::bvar(i - k)
            }
        }
        Expr::App(f, a) => crate::expr::app(lower_general(f, k, cut), lower_general(a, k, cut)),
        Expr::Lam { ty, body } => {
            crate::expr::lam(lower_general(ty, k, cut), lower_general(body, k, cut + 1))
        }
        Expr::Forall { ty, body } => {
            crate::expr::forall(lower_general(ty, k, cut), lower_general(body, k, cut + 1))
        }
        Expr::Let { ty, val, body } => std::rc::Rc::new(Expr::Let {
            ty: lower_general(ty, k, cut),
            val: lower_general(val, k, cut),
            body: lower_general(body, k, cut + 1),
        }),
        Expr::Proj { ind, idx, s } => std::rc::Rc::new(Expr::Proj {
            ind: ind.clone(),
            idx: *idx,
            s: lower_general(s, k, cut),
        }),
        Expr::Const(..) | Expr::Sort(..) | Expr::NatLit(..) | Expr::StrLit(..) => e.clone(),
    }
}
